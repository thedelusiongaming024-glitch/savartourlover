/** Converts a CuratedDestinationItem to the app's standard Destination interface */
export function curatedToDestination(c: CuratedDestinationItem): Destination {
  const coverScene: Scene = {
    key: (c.slug.replace(/-/g, "") as any) || "coxsbazar",
    label: c.name,
    imageUrl: c.imageUrl,
  };

  return {
    slug: c.slug,
    name: c.name,
    bn: c.bn,
    tagline: c.tagline,
    region: c.region,
    description: c.description,
    cover: coverScene,
    gallery: [coverScene],
    bestTime: c.bestTime,
    weather: c.weather,
    attractions: c.attractions,
    accommodation: "Boutique eco-resorts and verified partner hotels",
    travelTips: [
      "Carry national ID card or passport copy.",
      "Check weather and packing guidelines before departure.",
      "Book with Savar Tour Lover for verified local hosts and 24/7 travel support.",
    ],
    tourSlugs: [`tour_${c.slug}`],
  };
}
